/**
24. Найти номер последнего столбца, все элементы которого упорядочены по
убыванию.

номер последнего столбца не содержащего "0"
*/
#include <stdio.h>
#include <locale.h>
#include <malloc.h>


int main()
{
    setlocale(0,"");
    setlocale(LC_NUMERIC, "C");
    printf("\n---------------------------------------------------------------------\n");
    int n, m;
    do{
        printf("\nВведите количество строк n: ");
        scanf("%d", &n);
        if (n < 2 || n >= 100){
            printf("\n=====================================================================\n\t\t");
            printf("Ошибка: нарушен диапазон входных данных");
            printf("\n=====================================================================\n");
        }
    }while (n < 2 || n >= 100);
    printf("\n---------------------------------------------------------------------\n");
    do{
        printf("\nВведите количество столбцов m: ");
        scanf("%d", &m);
        if (m < 1 || m >= 100){
            printf("\n=====================================================================\n\t\t");
            printf("Ошибка: нарушен диапазон входных данных");
            printf("\n=====================================================================\n");
        }
    }while (m < 1 || m >= 100);
    printf("\n---------------------------------------------------------------------\n");
    double **A;
    int i,j;
    A = (double**)malloc(n * sizeof(double*));
    printf("\nВведите элементы массива A:\n");
    for (i = 0; i < n; i++){
        A[i] = (double*)malloc(m * sizeof(double));
        for (j = 0; j < m; j++){
            printf("\nA[%d][%d]: ", i+1, j+1);
            scanf("%lf", &A[i][j]);
        }
    }
    printf("\n---------------------------------------------------------------------\n\n");
    printf("Введено n: %d\n\n", n);
    printf("Введено m: %d\n\n", m);
    printf("Введён массив A:\n");
    printf(" ___");for(j=0;j<m;j++)printf(" ________");
    printf("\n|n\\m|");for(j=0;j<m;j++)printf("%5d   |",j+1);
    printf("\n ---");for(j=0;j<m;j++)printf("+--------");
    for(i=0;i<n;i++){
        printf("\n|%2d |",i+1);
        for(j=0;j<m;j++){
            printf("%8.2lf|",A[i][j]);
        }
    }
    printf("\n ===");for(j=0;j<m;j++)printf(" ========");

    printf("\n\n---------------------------------------------------------------------\n");
    int flag = 1;
    j = (m-1);
    while (j >= 0 && flag){
        i = 0;
        while (i < n && flag){
            if (A[i][j] != 0) i++;
            else flag = 0;
        }
        if (flag) flag = 0;
        else{
            j--;
            flag = 1;
        }
    }
    printf("\n=====================================================================\n\n\t\t");
    printf("Результат:\n\n");
    if (flag){
        printf("Нет столбцов с убыванием элементов.");
    }else{
        printf("Номер последнего столбца с убыванием элементов: %d", j+1);
    }
    printf("\n\n=====================================================================\n");

    for (i = 0; i < n; i++){
        free(A[i]);
    }
    free(A);
    return 0;
}
